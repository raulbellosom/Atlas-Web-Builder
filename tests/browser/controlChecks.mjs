import assert from 'node:assert/strict'

export async function checkControls(page, url, expect) {
  await page.goto(`${url}/?controls`)
  const values = () => page.getByTestId('values').textContent().then(JSON.parse)
  const combo = page.getByRole('combobox', { name: 'Familia' })
  await combo.fill('Segu')
  await expect(page.getByRole('option', { name: 'Segunda' })).toBeVisible()
  await page.keyboard.press('Enter')
  assert.equal((await values()).family, 'second')
  await page.getByRole('spinbutton', { name: 'Longitud' }).fill('24')
  await page.getByLabel('Unidad de Longitud').selectOption('rem')
  assert.equal((await values()).length, '24rem')
  await page.getByRole('switch', { name: 'Activar' }).check()
  assert.equal((await values()).enabled, true)
  await page.getByRole('button', { name: 'Aumentar Cantidad' }).click()
  assert.equal((await values()).amount, 21)
  await page.getByLabel('Color de prueba (hexadecimal)', { exact: true }).fill('#123456')
  assert.equal((await values()).color, '#123456')
  await page.getByLabel('Color de prueba (hexadecimal)', { exact: true }).fill('incorrecto')
  assert.equal((await values()).color, '#123456')
  const trigger = page.getByRole('button', { name: 'Detalles', exact: true })
  await trigger.click()
  await expect(page.getByRole('dialog', { name: 'Detalles' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  await page.getByRole('button', { name: 'Ayuda', exact: true }).focus()
  await expect(page.getByRole('tooltip')).toHaveText('Ayuda accesible')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('tooltip')).toHaveCount(0)
}
